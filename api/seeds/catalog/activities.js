/**
 * The activity templates, loaded by the catalog seed on every
 * `docker compose up`. A template already in the database is never
 * overwritten: the database is the catalog's home, so change a loaded
 * template there.
 *
 * Slots ({kid}, {pet}, {toy}, {toy2}, {toy3}, {interest}) are filled with the
 * family's words. The catalog knows toys only by name, so a template can't
 * assume what a toy is, and nothing may agree in gender with a slot ("cuando
 * aparezca", not "cuando lo encuentre"; "que lo elija {kid}", not "que {kid}
 * esté cansado"). Write "a {toy}" and "de {toy}" freely: they contract to
 * "al" and "del".
 *
 * `materials` holds, by key from src/materials/materials.js, what a template
 * can't be played without, and a family that has one of them marked off is
 * never offered it. `needs` says the same in words, with the alternatives. A
 * material with an alternative on the list ("una sábana o una manta") is
 * named once, by the key whose label covers both, and one with an alternative
 * every home has ("un pañuelo o un repasador") isn't named at all.
 *
 * `themes` holds, by key from src/catalog/themes.js, what a template is
 * about, and the ranking (JUG-104) favours it for a kid who loves one of
 * them. A template about nothing in particular leaves it empty.
 *
 * `categories` are the kinds of play a parent can ask for (JUG-30), and a
 * template carries every one that fits it, not only the main one. The test
 * for each is whether a parent who asked for that kind of play would be glad
 * to get this juego:
 *
 * - move: the kid's body is the game: running, jumping, climbing, dancing,
 *   carrying, throwing.
 * - create: the kid makes something: a drawing, a craft, a building, music.
 * - pretend: make-believe: role play, puppets, a toy or the grown-up playing
 *   a character.
 * - explore: nature, water and the senses, and finding out how something
 *   behaves.
 * - learn: it practises something with a name: counting, colours, sorting,
 *   memory, words.
 * - low_energy: the grown-up can sit or lie down and has nothing to prepare;
 *   calm games, quiet sensory play, the minutes before bed.
 * - helpers: a real job in the house: the kitchen, the laundry, the plants,
 *   the pet, the shopping.
 * - out_and_about: played away from home: the plaza, the street, an errand.
 *   Every outdoor template carries it.
 *
 * Batches 2 to 8 (JUG-24) cover ages 3 to 5, which batch 1 barely reached,
 * and the categories it never used: learn, helpers and out_and_about. They
 * are longer where the age allows it, up to six steps, and most need no toy,
 * so they reach families with a small toy box.
 *
 * Batch 9 (JUG-79) is low-energy, for ages 1 to 3, and written for the adult
 * rather than the kid: every one of them is played sitting or lying down, and
 * the last five are calm enough for the minutes before bed. They are three
 * steps, like batch 1.
 *
 * Batch 10 (JUG-80) is explore and helpers, for ages 1 to 3. The helpers are
 * real jobs a small kid can finish on their own, not pretend ones, and the
 * explore half is sensory: what the floor feels like, what the kitchen
 * smells like, and water in a basin on the balcony, whose safety rules say
 * plainly that a kid is never left alone with it.
 *
 * Batch 11 (JUG-176) is move, for ages 1 to 3: eight for an apartment, where
 * the noise and the neighbours are part of the design, and three for the
 * plaza, which the weather (JUG-25) brings up on a fine afternoon.
 *
 * Batch 12 (JUG-177) is ¿Qué suena?, the first discovery game: one template
 * per sound set, whose `game` names the set in src/games/sounds.js, so
 * Empezar opens the game instead of the timer. The grown-up sits with the
 * phone, so they are all low_energy and played inside, and the steps say how
 * to play; vehicles and the house get the kids moving, so they are medium.
 *
 * Batch 13 (JUG-179 to JUG-185) is seven more sets, played the same way:
 * instruments, the body, wild animals, the barrio and its birds, the
 * weather, and nature. Most are low, like the farm: the kids answer from
 * where they sit. The body and the wild animals are medium, because those
 * two are answered by acting the sound out. The ranking has every discovery
 * game share one freshness (JUG-128), so ten sets come up about as often as
 * three did.
 *
 * `rating`, from 1 to 5, is where every family's ranking starts before their
 * reactions move it (JUG-192, JUG-195). It is higher for original juegos kids
 * get into, and for the sound games. It is lower for dull or generic ones,
 * chores with little play in them, and juegos that need many materials or
 * something a family can't produce on demand, like a puddle or a hill. 3 is
 * neither way.
 *
 * Pending Alex's review and a voice pass (JUG-14).
 */

